export interface TreeEntry {
  readonly mode: string;
  readonly name: string;
  readonly oid: string;
}

export interface CommitView {
  readonly tree: string;
  readonly parents: string[];
  readonly author: string;
  readonly committer: string;
  readonly message: string;
}

export interface TagView {
  readonly object: string;
  readonly type: GitObjectType;
  readonly tag: string;
  readonly tagger: string;
  readonly message: string;
}

export function parseTree(data: Uint8Array): TreeEntry[] {
  const buffer = asBuffer(data);
  const entries: TreeEntry[] = [];
  let offset = 0;
  while (offset < buffer.length) {
    const space = buffer.indexOf(0x20, offset);
    if (space < 0) throw new Error('tree entry has no mode separator');
    const nul = buffer.indexOf(0x00, space + 1);
    if (nul < 0) throw new Error('tree entry has no name terminator');
    if (nul + 21 > buffer.length) throw new Error('tree entry has a truncated object id');
    const mode = buffer.subarray(offset, space).toString('ascii');
    const name = buffer.subarray(space + 1, nul).toString('utf8');
    const oid = buffer.subarray(nul + 1, nul + 21).toString('hex');
    entries.push({ mode, name, oid });
    offset = nul + 21;
  }
  return entries;
}

function compareTreeNames(a: { name: string; mode: string }, b: { name: string; mode: string }): number {
  const left = Buffer.from(a.mode === '40000' ? `${a.name}/` : a.name, 'utf8');
  const right = Buffer.from(b.mode === '40000' ? `${b.name}/` : b.name, 'utf8');
  return Buffer.compare(left, right);
}

export function buildTree(entries: ReadonlyArray<TreeEntry>): Buffer {
  const sorted = [...entries].sort(compareTreeNames);
  const parts: Buffer[] = [];
  for (const entry of sorted) {
    if (!isObjectId(entry.oid)) throw new Error(`tree entry ${entry.name} has a bad object id`);
    parts.push(Buffer.from(`${entry.mode} ${entry.name}\u0000`, 'utf8'));
    parts.push(Buffer.from(entry.oid, 'hex'));
  }
  return Buffer.concat(parts);
}

export function parseCommit(data: Uint8Array): CommitView {
  const buffer = asBuffer(data);
  const blank = buffer.indexOf('\n\n');
  const headerEnd = blank < 0 ? buffer.length : blank;
  const headerText = buffer.subarray(0, headerEnd).toString('utf8');
  const message = blank < 0 ? '' : buffer.subarray(blank + 2).toString('utf8');
  let tree = '';
  const parents: string[] = [];
  let author = '';
  let committer = '';
  for (const line of headerText.split('\n')) {
    if (!line) continue;
    const space = line.indexOf(' ');
    const key = space < 0 ? line : line.slice(0, space);
    const value = space < 0 ? '' : line.slice(space + 1);
    if (key === 'tree') tree = value;
    else if (key === 'parent') parents.push(value);
    else if (key === 'author') author = value;
    else if (key === 'committer') committer = value;
  }
  if (!isObjectId(tree)) throw new Error('commit has no valid tree header');
  return { tree, parents, author, committer, message };
}

export function parseTag(data: Uint8Array): TagView {
  const buffer = asBuffer(data);
  const blank = buffer.indexOf('\n\n');
  const headerEnd = blank < 0 ? buffer.length : blank;
  const headers = new Map<string, string>();
  for (const line of buffer.subarray(0, headerEnd).toString('utf8').split('\n')) {
    if (!line) continue;
    const space = line.indexOf(' ');
    if (space < 0) throw new Error(`tag header ${JSON.stringify(line)} has no value`);
    headers.set(line.slice(0, space), line.slice(space + 1));
  }
  const object = headers.get('object') ?? '';
  const type = headers.get('type') ?? '';
  if (!isObjectId(object)) throw new Error('tag has no valid object header');
  return {
    object,
    type: type as GitObjectType,
    tag: headers.get('tag') ?? '',
    tagger: headers.get('tagger') ?? '',
    message: blank < 0 ? '' : buffer.subarray(blank + 2).toString('utf8'),
  };
}

/** The identity every server-built commit/tag carries (fixed, so bytes are deterministic). */
export const FORGE_IDENTITY = 'Conformance <conformance@make.fun>';
/** A fixed commit timestamp (Unix seconds) for server-built commits: deterministic bytes. */
export const FORGE_TIMESTAMP = 1700000000;

export function buildCommit(fields: {
  tree: string;
  parents?: readonly string[];
  message: string;
  author?: string;
  committer?: string;
  timestamp?: number;
  timezone?: string;
}): Buffer {
  if (!isObjectId(fields.tree)) throw new Error('buildCommit needs a valid tree id');
  const timestamp = fields.timestamp ?? FORGE_TIMESTAMP;
  const timezone = fields.timezone ?? '+0000';
  const who = `${fields.author ?? FORGE_IDENTITY} ${timestamp} ${timezone}`;
  const committer = `${fields.committer ?? FORGE_IDENTITY} ${timestamp} ${timezone}`;
  const lines = [`tree ${fields.tree}`];
  for (const parent of fields.parents ?? []) lines.push(`parent ${parent}`);
  lines.push(`author ${who}`, `committer ${committer}`, '');
  return Buffer.from(`${lines.join('\n')}\n${fields.message}`, 'utf8');
}

export function buildTag(fields: {
  object: string;
  type: GitObjectType;
  tag: string;
  message: string;
  tagger?: string;
  timestamp?: number;
  timezone?: string;
}): Buffer {
  if (!isObjectId(fields.object)) throw new Error('buildTag needs a valid object id');
  const timestamp = fields.timestamp ?? FORGE_TIMESTAMP;
  const timezone = fields.timezone ?? '+0000';
  const tagger = `${fields.tagger ?? FORGE_IDENTITY} ${timestamp} ${timezone}`;
  return Buffer.from(
    `object ${fields.object}\ntype ${fields.type}\ntag ${fields.tag}\ntagger ${tagger}\n\n${fields.message}`,
    'utf8',
  );
}

export function objectHeader(type: GitObjectType, size: number): Buffer {
  return Buffer.from(`${type} ${size}\u0000`, 'utf8');
}

export function hashObject(type: GitObjectType, data: Uint8Array): string {
  const body = asBuffer(data);
  const hash = createHash('sha1');
  hash.update(objectHeader(type, body.length));
  hash.update(body);
  return hash.digest('hex');
}

export type ObjectLookup = (oid: string) => GitObject | undefined;

/**
 * Every object reachable from `roots`: commit -> tree + parents, tree -> entries (gitlinks skipped),
 * tag -> its target. `maxDepth` limits the commit walk (a commit at distance `maxDepth - 1` is
 * included, its parents are not); trees/blobs of an included commit are always fully included.
 * `stopAt` names commits whose parents are never traversed (a shallow client's held boundaries).
 */
export function collectReachable(
  roots: Iterable<string>,
  lookup: ObjectLookup,
  options: { maxDepth?: number; stopAt?: ReadonlySet<string> } = {},
): Set<string> {
  const seen = new Set<string>();
  const maxDepth = options.maxDepth ?? Number.POSITIVE_INFINITY;
  const stopAt = options.stopAt;
  // Queue of [oid, depth] where depth counts commit generations from a root (tags resolve at the
  // same depth as their target's walk).
  const queue: Array<{ oid: string; depth: number }> = [];
  for (const root of roots) if (isObjectId(root)) queue.push({ oid: root, depth: 0 });
  while (queue.length) {
    const { oid, depth } = queue.pop()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (!object) continue;
    seen.add(oid);
    if (object.type === 'commit') {
      if (depth >= maxDepth) continue;
      if (stopAt?.has(oid)) continue;
      const commit = parseCommit(object.data);
      queue.push({ oid: commit.tree, depth });
      for (const parent of commit.parents) queue.push({ oid: parent, depth: depth + 1 });
    } else if (object.type === 'tag') {
      queue.push({ oid: parseTag(object.data).object, depth });
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push({ oid: entry.oid, depth });
      }
    }
  }
  return seen;
}

/** The objects reachable from `newTips` (within `maxDepth`) that `heldTips` does not already hold. */
export function objectsToSend(
  lookup: ObjectLookup,
  heldTips: Iterable<string>,
  newTips: Iterable<string>,
  options: { maxDepth?: number; stopAt?: ReadonlySet<string> } = {},
): GitObject[] {
  const held = collectReachable(heldTips, lookup, { stopAt: options.stopAt });
  const wanted = collectReachable(newTips, lookup, { maxDepth: options.maxDepth });
  const send: GitObject[] = [];
  for (const oid of wanted) {
    if (held.has(oid)) continue;
    const object = lookup(oid);
    if (object) send.push({ type: object.type, data: object.data });
  }
  return send;
}

/** Is `ancestor` an ancestor of (or equal to) `oid`? Walks the commit graph from `oid`. */
export function isAncestor(lookup: ObjectLookup, ancestor: string, oid: string): boolean {
  if (ancestor === oid) return true;
  const seen = new Set<string>();
  const queue = [oid];
  while (queue.length) {
    const current = queue.pop()!;
    if (seen.has(current)) continue;
    seen.add(current);
    const object = lookup(current);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) {
      if (parent === ancestor) return true;
      queue.push(parent);
    }
  }
  return false;
}

/** The merge-base of two commits (the newest common ancestor, by first-parent walk order). */
export function mergeBase(lookup: ObjectLookup, a: string, b: string): string | null {
  const ancestorsA = new Set<string>();
  const queueA = [a];
  while (queueA.length) {
    const current = queueA.pop()!;
    if (ancestorsA.has(current)) continue;
    ancestorsA.add(current);
    const object = lookup(current);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) queueA.push(parent);
  }
  const queueB = [b];
  const seenB = new Set<string>();
  while (queueB.length) {
    const current = queueB.pop()!;
    if (seenB.has(current)) continue;
    seenB.add(current);
    if (ancestorsA.has(current)) return current;
    const object = lookup(current);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) queueB.push(parent);
  }
  return null;
}

/** A flat map of path -> {oid, mode} for a tree, recursively. */
export function flattenTree(lookup: ObjectLookup, treeOid: string, prefix = ''): Map<string, { oid: string; mode: string }> {
  const out = new Map<string, { oid: string; mode: string }>();
  const object = lookup(treeOid);
  if (!object || object.type !== 'tree') return out;
  for (const entry of parseTree(object.data)) {
    const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.mode === '40000') {
      for (const [subPath, value] of flattenTree(lookup, entry.oid, path)) out.set(subPath, value);
    } else {
      out.set(path, { oid: entry.oid, mode: entry.mode });
    }
  }
  return out;
}

/** Build a tree object from a flat path map, creating intermediate trees. Returns the root tree oid. */
export function buildTreeFromPaths(
  lookup: ObjectLookup,
  store: (type: GitObjectType, data: Buffer) => string,
  paths: Map<string, { oid: string; mode: string }>,
): string {
  // Group paths by their first segment, recursively.
  const build = (entries: Array<{ name: string; rest: string[]; oid: string; mode: string }>): string => {
    const byName = new Map<string, Array<{ name: string; rest: string[]; oid: string; mode: string }>>();
    for (const entry of entries) {
      const list = byName.get(entry.name) ?? [];
      list.push(entry);
      byName.set(entry.name, list);
    }
    const treeEntries: TreeEntry[] = [];
    for (const [name, list] of byName) {
      if (list.length === 1 && list[0]!.rest.length === 0) {
        treeEntries.push({ mode: list[0]!.mode, name, oid: list[0]!.oid });
      } else {
        const sub = list.map((entry) => ({ name: entry.rest[0]!, rest: entry.rest.slice(1), oid: entry.oid, mode: entry.mode }));
        const subOid = build(sub);
        treeEntries.push({ mode: '40000', name, oid: subOid });
      }
    }
    const data = buildTree(treeEntries);
    return store('tree', data);
  };
  const entries = [...paths.entries()].map(([path, value]) => {
    const parts = path.split('/');
    return { name: parts[0]!, rest: parts.slice(1), oid: value.oid, mode: value.mode };
  });
  if (entries.length === 0) return store('tree', buildTree([]));
  return build(entries);
}

